// Synthetic native responses only; no real account, network or files are accessed.
const { JSDOM } = require('jsdom');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const frontend = path.join(__dirname, '../frontend');
(async () => {
  const dom = new JSDOM(fs.readFileSync(path.join(frontend, 'index.html'), 'utf8'), { url: 'https://fixture.invalid', runScripts: 'outside-only' });
  const w = dom.window;
  const add = w.document.addEventListener.bind(w.document);
  w.document.addEventListener = (type, ...args) => { if (type !== 'DOMContentLoaded') add(type, ...args); };
  let result = { limit_bytes: 2e9, used_bytes: 500e6, reserved_bytes: 100e6, enabled: true };
  let reject = false;
  let delayed = null;
  w.__TAURI__ = { core: { invoke: async command => {
    if (command !== 'cloud_storage_usage') return null;
    if (reject) throw new Error('Synthetic failure');
    if (delayed) return delayed;
    return result;
  } }, event: { listen: async () => () => {} } };
  w.setInterval = () => 0;
  w.eval(fs.readFileSync(path.join(frontend, 'main.js'), 'utf8') + `;window.storageTest={loadAccountStorage,setUser(user){currentUserInfo=user},text(id){return document.getElementById(id).textContent}};`);
  const t = w.storageTest;
  const user = { id: 1, plan_tier: 'pro', plan_active: true };
  t.setUser(user);
  await t.loadAccountStorage(user);
  assert.match(t.text('account-storage-remaining'), /1.4 GB of 2 GB remaining/);
  assert.match(t.text('account-storage-detail'), /100 MB reserved for uploads/);
  assert.equal(w.document.getElementById('account-storage-meter').value, 30);
  result = { ...result, used_bytes: 2e9, reserved_bytes: 0 };
  await t.loadAccountStorage(user);
  assert.match(t.text('account-storage-remaining'), /^0 B of 2 GB remaining/);
  result = { ...result, limit_bytes: 4e9, used_bytes: 1e9, enabled: false };
  await t.loadAccountStorage(user);
  assert.match(t.text('account-storage-remaining'), /3 GB of 4 GB remaining/, 'quota comes from the server');
  assert.match(t.text('account-storage-note'), /currently unavailable/);
  reject = true;
  await t.loadAccountStorage(user);
  assert.equal(t.text('account-storage-remaining'), 'Storage usage unavailable');
  assert.equal(w.document.getElementById('account-storage-meter').hidden, true);
  assert.equal(w.document.getElementById('account-storage-refresh').disabled, false);
  reject = false;
  let finish;
  delayed = new Promise(resolve => finish = resolve);
  const pending = t.loadAccountStorage(user);
  t.setUser(null);
  await t.loadAccountStorage(null);
  finish(result);
  await pending;
  assert.equal(t.text('account-storage-remaining'), 'Sign in to see your storage', 'late account response cannot expose previous account usage');
  assert.equal(t.text('account-storage-detail'), '');
  dom.window.close();
  console.log('Account storage: remaining quota, upload reservations, custom limits, errors and account-switch isolation passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
